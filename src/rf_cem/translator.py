"""Translate the 500 MHz baseline UDSG into CST v0 action/script artifacts."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path, PureWindowsPath
from typing import Literal

from .history_templates import CstHistoryBlock, CstHistoryTemplates


FilenameMode = Literal["star-basename", "absolute"]


@dataclass(frozen=True)
class TranslationArtifacts:
    """Generated CSTTranslator v0 artifacts."""

    actions: list[dict]
    mapping_table: dict
    script: str
    report: dict


def emit_step_import_block(
    step_file: Path,
    *,
    filename_mode: FilenameMode = "star-basename",
    scale_to_unit: str = "0",
    import_id: str = "1",
    import_curves: str = "True",
    import_attributes: str = "True",
    import_curve_attributes: str = "True",
) -> str:
    """Emit the observed CST VBA STEP import block."""
    filename = _step_filename_argument(step_file, filename_mode)
    return "\n".join(
        [
            "With STEP",
            "     .Reset",
            f"     .ScaleToUnit \"{scale_to_unit}\"",
            f"     .FileName \"{filename}\"",
            f"     .Id \"{import_id}\"",
            "     .Version \"11.0\"",
            "     .ImportToActiveCoordinateSystem \"True\"",
            f"     .Curves \"{import_curves}\"",
            f"     .ImportAttributes \"{import_attributes}\"",
            f"     .ImportCurveAttributes \"{import_curve_attributes}\"",
            "     .UpdateMaterialPropertiesFromMaterialLibrary \"False\"",
            "     .Read",
            "End With",
        ]
    )


def emit_assign_imported_vacuum_material_block(
    *,
    imported_solid_name: str = "default:Open CASCADE STEP translator 7.7 1",
    material_name: str = "Vacuum",
) -> str:
    """Assign the imported RF vacuum body to CST's Vacuum material.

    Evidence source: live-CST ModelHistory generated by changing the imported
    STEP solid material to Vacuum in CST 2026.  Length/frequency units are not
    changed by this action.
    """
    return f'Solid.ChangeMaterial "{imported_solid_name}", "{material_name}"'


